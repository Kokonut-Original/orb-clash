  const xf=(d,tx,ty,s)=>d.replace(/([MLCZ])([^MLCZ]*)/g,(m,k,nums)=>{if(k==="Z")return"Z";const v=nums.trim().split(/[\s,]+/).map(Number);const o=[];for(let i=0;i<v.length;i+=2)o.push(f(v[i]*s+tx),f(v[i+1]*s+ty));return k+o.join(" ")});
