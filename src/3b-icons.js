  const seg=(x1,y1,x2,y2,w)=>{const dx=x2-x1,dy=y2-y1,l=Math.hypot(dx,dy)||1,nx=-dy/l*w/2,ny=dx/l*w/2;return p(f(x1+nx),f(y1+ny),f(x2+nx),f(y2+ny),f(x2-nx),f(y2-ny),f(x1-nx),f(y1-ny))};
